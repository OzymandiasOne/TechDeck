"""
TechDeck Fidget Spinner

A standalone, frameless, always-on-top fidget spinner drawn as HAND-EDITABLE
PIXEL ART, like the moth (`MOTH_FRAMES`): edit the `SPINNER_ART` grid below.

It's a four-arm spinner kept PERFECTLY 4-fold symmetric by construction: you only
draw ONE arm — the TOP arm plus the top half of the hub — and `_enforce_4fold`
rotates it 90/180/270 into the other three arms at load. So edit the top of the
grid; whatever you put in the other three arms is ignored (overwritten by the
rotated top arm). The grid is rendered to a pixmap once; spinning rotates that
pixmap with smoothing OFF, so the pixels stay hard-edged at every angle.

Editing the art — each cell is one character:
    .  transparent (a dark OUTLINE is auto-traced around every filled cell,
       and around the bearing holes, just like the moth's silhouette outline)
    B  body  -> theme accent_pressed   (the hub + the arms)
    W  wing  -> theme accent_two        (the lobes / "wings")
    R  ring  -> theme text              (the bright bearing rings)
    H  highlight -> a lighter wing tone (optional shading; place by hand)
    o  outline tone                     (optional hand-drawn dark detail)

Keep the grid SQUARE and ODD-sized (so it has a true centre cell), keep the hub
centred, and keep art within the inscribed circle (radius = half the grid) or it
clips as it spins. Keep every row the same length.

  - Click anywhere on it to add spin (and drag to move it).
  - It does NOT close on double-click (that fought with clicking to spin);
    `/clear` puts it away (see CommandHandler.stop_session_effects).

Tip: preview edits without launching the whole app with
`python tools/preview_spinner.py`.
"""

